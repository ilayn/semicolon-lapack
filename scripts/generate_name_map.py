#!/usr/bin/env python3
"""Generate lapack_name_map.h from public header declarations.

Reads all SEMICOLON_API function declarations from the precision and auxiliary
headers, and produces a renaming header that maps each function name through
the LAPACK_NAME() macro. semicolon_lapack.h includes this header whenever
LAPACK_NAME is defined, that is for ILP64 builds and for builds with a custom
SYMBOL_MANGLING.

Usage:
    python scripts/generate_name_map.py           # rewrite the header
    python scripts/generate_name_map.py --check   # exit 1 if it is stale
"""

import argparse
import re
import os
import sys

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
PROJECT_ROOT = os.path.dirname(SCRIPT_DIR)
INCLUDE_DIR = os.path.join(PROJECT_ROOT, "src", "include")

HEADERS = [
    "semicolon_lapack_double.h",
    "semicolon_lapack_single.h",
    "semicolon_lapack_complex_double.h",
    "semicolon_lapack_complex_single.h",
    "semicolon_lapack_auxiliary.h",
]

OUTPUT = os.path.join(INCLUDE_DIR, "lapack_name_map.h")

# Matches: SEMICOLON_API <return_type> <function_name>(
DECL_RE = re.compile(r"SEMICOLON_API\s+\w+\s+(\w+)\s*\(")
MAP_RE = re.compile(r"^#define (\w+) LAPACK_NAME\(")


def extract_functions(header_path):
    """Extract function names from a header file."""
    names = []
    with open(header_path) as f:
        for line in f:
            m = DECL_RE.search(line)
            if m:
                names.append(m.group(1))
    return names


def render(unique_names):
    lines = [
        "/* Auto-generated by scripts/generate_name_map.py — do not edit.\n",
        "   Regenerate with: python scripts/generate_name_map.py */\n",
        "#ifndef SEMICOLON_LAPACK_NAME_MAP_H\n",
        "#define SEMICOLON_LAPACK_NAME_MAP_H\n",
        "\n",
    ]
    lines += [f"#define {name} LAPACK_NAME({name})\n" for name in unique_names]
    lines += ["\n", "#endif /* SEMICOLON_LAPACK_NAME_MAP_H */\n"]
    return "".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check", action="store_true",
        help="Do not write; exit 1 if the header differs from the declarations"
    )
    args = parser.parse_args()

    all_names = []
    per_header = {}

    for header in HEADERS:
        path = os.path.join(INCLUDE_DIR, header)
        names = extract_functions(path)
        per_header[header] = len(names)
        all_names.extend(names)

    # Check for duplicates
    seen = {}
    duplicates = []
    for name in all_names:
        if name in seen:
            duplicates.append((name, seen[name]))
        else:
            seen[name] = name

    unique_names = sorted(seen.keys())
    content = render(unique_names)

    if args.check:
        with open(OUTPUT, encoding="utf-8") as f:
            current = f.read()
        if current == content:
            print(f"{OUTPUT} is up to date ({len(unique_names)} functions)")
            return 0
        mapped = {m.group(1) for line in current.splitlines()
                  if (m := MAP_RE.match(line))}
        missing = sorted(set(unique_names) - mapped)
        extra = sorted(mapped - set(unique_names))
        print(f"{OUTPUT} is stale; run python scripts/generate_name_map.py")
        if missing:
            print(f"  missing ({len(missing)}): {' '.join(missing)}")
        if extra:
            print(f"  not declared ({len(extra)}): {' '.join(extra)}")
        return 1

    # Write the output header
    with open(OUTPUT, "w", encoding="utf-8") as f:
        f.write(content)

    # Summary
    print(f"Generated {OUTPUT}")
    print(f"Total unique functions: {len(unique_names)}")
    for header, count in per_header.items():
        print(f"  {header}: {count}")
    if duplicates:
        print(f"Duplicates found (across headers, deduplicated): {len(duplicates)}")
    else:
        print("No duplicates found.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
